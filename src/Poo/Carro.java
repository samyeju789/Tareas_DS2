package Poo;

public class Carro {
    public String marca;
    public String modelo;
    public int year;
    public String molde;
    public String volante;
    public int motor;
    public String placa;
    public String tipo;
    public String caja;
    public String combustible;
    public int puertas;

    public Carro(String marca, String modelo, int year, String molde, String volante, int motor, String placa, String tipo, String caja, String combustible, int puertas) {
        this.marca = marca;
        this.modelo = modelo;
        this.year = year;
        this.molde = molde;
        this.volante = volante;
        this.motor = motor;
        this.placa = placa;
        this.tipo = tipo;
        this.caja = caja;
        this.combustible = combustible;
        this.puertas = puertas;
    }
}