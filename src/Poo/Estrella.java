package Poo;

public class Estrella {
    public String color;
    public int puntas;
    public String tamano;
    public int esquinas;
    public int brillo;

    public Estrella(String color, int puntas, String tamano, int esquinas, int brillo) {
        this.color = color;
        this.puntas = puntas;
        this.tamano = tamano;
        this.esquinas = esquinas;
        this.brillo = brillo;
    }
}
